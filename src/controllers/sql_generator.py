import re
from typing import List, Tuple

from ..models.project import Project
from ..models.entity import Entity
from ..models.association import Association
from ..models.link import Link
from ..models.attribute import Attribute
from ..utils.constants import DATA_TYPES, SIZED_DATA_TYPES
from .pg_keywords import QUOTED_KEYWORDS

# Names that PostgreSQL accepts unquoted, as in its own quote_ident()
_PLAIN_IDENTIFIER = re.compile(r"[a-z_][a-z0-9_]*")

# Model types whose PostgreSQL spelling differs
_POSTGRES_TYPES = {"DOUBLE": "DOUBLE PRECISION"}

# (table, column, referenced table, referenced column), all quoted
ForeignKey = Tuple[str, str, str, str]


class SQLGenerator:
    """Generates PostgreSQL DDL from MCD model."""

    def __init__(self, project: Project):
        self._project = project

    def generate(self) -> str:
        """Generate complete SQL DDL script.

        Tables come first and foreign keys after them, as ALTER TABLE statements,
        so that the script runs whatever the order of the tables and even when two
        tables reference each other.
        """
        lines = []
        lines.append("-- Generated by Merisio")
        lines.append("-- PostgreSQL DDL")
        lines.append("")

        foreign_keys: List[ForeignKey] = []

        # Generate tables for entities
        for entity in self._project.get_all_entities():
            table_sql = self._generate_entity_table(entity, foreign_keys)
            if table_sql:
                lines.append(table_sql)
                lines.append("")

        # Analyze associations and generate appropriate structures
        for assoc in self._project.get_all_associations():
            assoc_sql = self._generate_association_table(assoc, foreign_keys)
            if assoc_sql:
                lines.append(assoc_sql)
                lines.append("")

        if foreign_keys:
            lines.append("-- Foreign keys")
            for table, column, ref_table, ref_column in foreign_keys:
                lines.append(
                    f"ALTER TABLE {table} ADD FOREIGN KEY ({column}) "
                    f"REFERENCES {ref_table}({ref_column});"
                )
            lines.append("")

        return "\n".join(lines)

    def _generate_entity_table(self, entity: Entity, foreign_keys: List[ForeignKey]) -> str:
        """Generate CREATE TABLE statement for an entity."""
        table_name = self._quote(self._safe_name(entity.name))
        lines = []
        lines.append(f"CREATE TABLE {table_name} (")

        columns = []
        pk_columns = []

        # Add columns from entity's own attributes
        for attr in entity.attributes:
            col_name = self._quote(self._get_column_name(entity.name, attr.name))
            col_def = f"    {col_name} {self._column_type(attr)}"
            if attr.is_primary_key:
                pk_columns.append(col_name)
            columns.append(col_def)

        # Check if we need to add foreign keys from 1,1 or 0,1 relationships
        links = self._project.get_links_for_entity(entity.id)
        for link in links:
            if link.cardinality_max == "1":  # This entity has (x,1) cardinality
                # Get the other entity through the association
                assoc_links = self._project.get_links_for_association(link.association_id)
                for other_link in assoc_links:
                    if other_link.entity_id != entity.id and other_link.cardinality_max == "N":
                        # This is a N-1 relationship, add FK to this entity
                        other_entity = self._project.get_entity(other_link.entity_id)
                        if other_entity:
                            for pk_attr in other_entity.get_primary_keys():
                                # Original FK name before override
                                original_fk_name = f"fk_{self._safe_name(other_entity.name)}_{pk_attr.name}"
                                col_name = self._quote(self._get_column_name(entity.name, original_fk_name))
                                ref_col = self._quote(self._get_column_name(other_entity.name, pk_attr.name))
                                columns.append(f"    {col_name} {self._column_type(pk_attr)}")
                                foreign_keys.append((
                                    table_name, col_name,
                                    self._quote(self._safe_name(other_entity.name)), ref_col,
                                ))

        # Add primary key constraint
        if pk_columns:
            columns.append(f"    PRIMARY KEY ({', '.join(pk_columns)})")

        lines.append(",\n".join(columns))
        lines.append(");")

        return "\n".join(lines)

    def _generate_association_table(self, assoc: Association, foreign_keys: List[ForeignKey]) -> str:
        """Generate CREATE TABLE for associations that need junction tables."""
        links = self._project.get_links_for_association(assoc.id)

        if len(links) < 2:
            return ""

        # Check if this is a N-N relationship (needs junction table)
        multiple_links = [link for link in links if link.cardinality_max == "N"]

        # Also create junction table if association has carrying attributes
        if len(multiple_links) >= 2 or assoc.has_attributes():
            return self._generate_junction_table(assoc, links, foreign_keys)

        return ""

    def _generate_junction_table(self, assoc: Association, links: List[Link],
                                 foreign_keys: List[ForeignKey]) -> str:
        """Generate a junction table for N-N relationships."""
        lines = []
        table_name = self._quote(self._safe_name(assoc.name))
        lines.append(f"CREATE TABLE {table_name} (")

        columns = []
        pk_columns = []

        # Add foreign key columns for each linked entity
        for link in links:
            entity = self._project.get_entity(link.entity_id)
            if entity:
                for pk_attr in entity.get_primary_keys():
                    # Original FK name before override
                    original_fk_name = f"fk_{self._safe_name(entity.name)}_{pk_attr.name}"
                    col_name = self._quote(self._get_column_name(assoc.name, original_fk_name))
                    ref_col = self._quote(self._get_column_name(entity.name, pk_attr.name))
                    columns.append(f"    {col_name} {self._column_type(pk_attr)} NOT NULL")
                    pk_columns.append(col_name)
                    foreign_keys.append((
                        table_name, col_name, self._quote(self._safe_name(entity.name)), ref_col,
                    ))

        # Add carrying attributes (association's own attributes)
        for attr in assoc.attributes:
            col_name = self._quote(self._get_column_name(assoc.name, attr.name))
            columns.append(f"    {col_name} {self._column_type(attr)}")

        # Add primary key (composite of all foreign keys)
        if pk_columns:
            columns.append(f"    PRIMARY KEY ({', '.join(pk_columns)})")

        lines.append(",\n".join(columns))
        lines.append(");")

        return "\n".join(lines)

    def _column_type(self, attr: Attribute) -> str:
        """PostgreSQL type of a column, refusing anything but a known type and size.

        Project files are validated on load; this check stops any other path from
        putting arbitrary text into the generated SQL.
        """
        data_type = attr.data_type.upper()
        if data_type not in DATA_TYPES:
            raise ValueError(f"unknown data type {attr.data_type!r} for attribute {attr.name!r}")
        sql_type = _POSTGRES_TYPES.get(data_type, data_type)

        if attr.size is not None and data_type in SIZED_DATA_TYPES:
            if isinstance(attr.size, bool) or not isinstance(attr.size, int) or attr.size < 1:
                raise ValueError(f"invalid size {attr.size!r} for attribute {attr.name!r}")
            return f"{sql_type}({attr.size})"
        return sql_type

    @staticmethod
    def _quote(name: str) -> str:
        """Quote an identifier when PostgreSQL requires it, as its quote_ident() does."""
        if _PLAIN_IDENTIFIER.fullmatch(name) and name not in QUOTED_KEYWORDS:
            return name
        return '"' + name.replace('"', '""') + '"'

    def _safe_name(self, name: str) -> str:
        """Convert name to safe SQL identifier."""
        # Convert to lowercase and replace spaces with underscores
        safe = name.lower().replace(" ", "_").replace("-", "_")
        # Remove any non-alphanumeric characters except underscore
        safe = "".join(c for c in safe if c.isalnum() or c == "_")
        return safe

    def _get_column_name(self, table_name: str, original_name: str) -> str:
        """Get the column name, applying any MLD overrides."""
        # Table names in MLD are uppercase
        override = self._project.get_mld_column_name(table_name.upper(), original_name)
        return self._safe_name(override)
