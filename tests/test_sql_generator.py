class TestSQLGenerator:
    """Tests for SQL generation."""

    def test_generate_simple_table(self, simple_project):
        """Test generating a simple table."""
        generator = SQLGenerator(simple_project)
        sql = generator.generate()

        assert "CREATE TABLE client" in sql
        assert "id_client INT" in sql
        assert "nom VARCHAR(100)" in sql
        assert "email VARCHAR(255)" in sql
        assert "PRIMARY KEY (id_client)" in sql

    def test_generate_junction_table(self, n_n_relationship_project):
        """Test generating junction table for N-N relationship."""
        generator = SQLGenerator(n_n_relationship_project)
        sql = generator.generate()

        # Check entity tables
        assert "CREATE TABLE etudiant" in sql
        assert "CREATE TABLE cours" in sql

        # Check junction table
        assert "CREATE TABLE inscription" in sql
        assert "fk_etudiant_id_etudiant" in sql
        assert "fk_cours_id_cours" in sql
        assert "note DECIMAL(5)" in sql  # Carrying attribute
        assert "FOREIGN KEY" in sql

    def test_safe_name_conversion(self, simple_project):
        """Test that names are converted to safe SQL identifiers."""
        generator = SQLGenerator(simple_project)

        # Add entity with special characters
        simple_project.add_entity(Entity(
            name="Produit Special",
            attributes=[
                Attribute(name="id_produit", data_type="INT", is_primary_key=True)
            ]
        ))

        sql = generator.generate()

        # Should be lowercase with underscores
        assert "produit_special" in sql

    def test_empty_project(self):
        """Test generating SQL for empty project."""
        project = Project()
        generator = SQLGenerator(project)
        sql = generator.generate()

        assert "Generated by Merisio" in sql
        assert "CREATE TABLE" not in sql


class TestPostgresValidity:
    """The DDL must run on PostgreSQL."""

    @staticmethod
    def _project_with(*entities):
        project = Project()
        for entity in entities:
            project.add_entity(entity)
        return project

    def test_reserved_words_are_quoted(self):
        project = self._project_with(Entity(name="Order", attributes=[
            Attribute(name="id", data_type="INT", is_primary_key=True),
            Attribute(name="select", data_type="TEXT"),
        ]))
        sql = SQLGenerator(project).generate()
        assert 'CREATE TABLE "order" (' in sql
        assert '"select" TEXT' in sql
        assert "PRIMARY KEY (id)" in sql

    def test_names_postgres_cannot_take_unquoted_are_quoted(self):
        project = self._project_with(Entity(name="2fa", attributes=[
            Attribute(name="id", data_type="INT", is_primary_key=True)]))
        assert 'CREATE TABLE "2fa" (' in SQLGenerator(project).generate()

    def test_ordinary_names_stay_unquoted(self, simple_project):
        sql = SQLGenerator(simple_project).generate()
        assert "CREATE TABLE client (" in sql
        assert '"' not in sql

    def test_double_becomes_double_precision(self):
        project = self._project_with(Entity(name="Reading", attributes=[
            Attribute(name="id", data_type="INT", is_primary_key=True),
            Attribute(name="value", data_type="DOUBLE")]))
        assert "value DOUBLE PRECISION" in SQLGenerator(project).generate()

    def test_foreign_keys_follow_all_tables(self, n_n_relationship_project):
        sql = SQLGenerator(n_n_relationship_project).generate()
        last_table = sql.rindex("CREATE TABLE")
        first_fk = sql.index("ALTER TABLE")
        assert last_table < first_fk
        assert "ALTER TABLE inscription ADD FOREIGN KEY (fk_etudiant_id_etudiant) " \
               "REFERENCES etudiant(id_etudiant);" in sql
        # No inline constraint can reference a table that does not exist yet
        assert "    FOREIGN KEY" not in sql

    def test_unknown_type_never_reaches_the_sql(self):
        project = self._project_with(Entity(name="T", attributes=[
            Attribute(name="x", data_type="INT); DROP TABLE t; --")]))
        with pytest.raises(ValueError, match="unknown data type"):
            SQLGenerator(project).generate()

    def test_non_integer_size_never_reaches_the_sql(self):
        project = self._project_with(Entity(name="T", attributes=[
            Attribute(name="x", data_type="VARCHAR", size="1); DROP TABLE t; --")]))
        with pytest.raises(ValueError, match="invalid size"):
            SQLGenerator(project).generate()
